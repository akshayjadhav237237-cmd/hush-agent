"""Real desktop test: Graphify AST graph build, incremental update, and stall alert."""
import os
import shutil
import tempfile
import pytest

from core.checkpoint import RunState
from core.graph_tools import GraphTools
from core.notify import Notifier
from tests_real.real_test_helper import record_result, sha256_text


def test_real_desktop_graphify_flow() -> None:
    # Create scratch Python project
    scratch_dir = tempfile.mkdtemp(prefix="hush_graphify_test_")
    try:
        # Create initial Python module
        module_a = os.path.join(scratch_dir, "calculator.py")
        with open(module_a, "w", encoding="utf-8") as f:
            f.write("def add(a: int, b: int) -> int:\n    return a + b\n")

        alerts: list[str] = []

        def mock_ask_human(prompt: str) -> str:
            alerts.append(prompt)
            return "Human acknowledges stall"

        notifier = Notifier(topic=None, input_fn=lambda: "continue")
        notifier.ask_human = mock_ask_human  # type: ignore

        state = RunState(run_id="test_graphify", idea="test", step=1)
        tools = GraphTools(
            project_dir=scratch_dir,
            notifier=notifier,
            audit=None,
            state=state,
        )

        # 1. Build graph
        build_output = tools.graph_build()
        assert "Graph HTML:" in build_output

        report_file = os.path.join(scratch_dir, "graphify-out", "GRAPH_REPORT.md")
        assert os.path.exists(report_file), "GRAPH_REPORT.md was not generated by Graphify"
        with open(report_file, "r", encoding="utf-8") as f:
            report_v1 = f.read()
        assert len(report_v1) > 0

        # 2. Add new file and update
        module_b = os.path.join(scratch_dir, "formatter.py")
        with open(module_b, "w", encoding="utf-8") as f:
            f.write("def format_sum(a: int, b: int) -> str:\n    return f'Sum: {a + b}'\n")

        tools.graph_update()
        with open(report_file, "r", encoding="utf-8") as f:
            report_v2 = f.read()

        assert report_v2 != report_v1, "Report should update after new code is added"
        assert state.graph_stalls == 0

        # 3. Update without changes (Round 1 stall)
        tools.graph_update()
        assert state.graph_stalls == 1
        assert len(alerts) == 0

        # 4. Update without changes again (Round 2 stall -> triggers alert)
        tools.graph_update()
        assert state.graph_stalls == 2
        assert len(alerts) == 1
        assert "not changed for 2 rounds" in alerts[0]

        record_result(
            feature_id="safety-graph-stall",
            status="PASS",
            detail="Graphify real extraction verified: builds AST, updates on new files, and trips alert on 2 consecutive unchanged rounds.",
            evidence_hash=sha256_text(report_v2),
        )
    finally:
        shutil.rmtree(scratch_dir, ignore_errors=True)
