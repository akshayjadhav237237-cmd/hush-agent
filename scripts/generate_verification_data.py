"""Generate verification data and export real replay for Hush.

This script:
1. Parses verification/real_desktop_results.json.
2. Exports typed structured data to src/data/verification.ts with status:
   "Verified on a real desktop (date)" if PASS, else "Not yet verified".
3. Identifies the latest real run with an audit.jsonl in agent/runs/.
4. Invokes agent.export_replay to export public/replay_real.json with mode "real".
5. Verifies public/replay_real.json contains valid JSON and mode "real".
"""
from __future__ import annotations

import datetime
import json
import os
import shutil
import sys
from typing import Any

# Ensure project root and agent directory are on sys.path
REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AGENT_DIR = os.path.join(REPO_ROOT, "agent")
if REPO_ROOT not in sys.path:
    sys.path.insert(0, REPO_ROOT)
if AGENT_DIR not in sys.path:
    sys.path.insert(0, AGENT_DIR)

from export_replay import export_replay  # type: ignore


VERIFICATION_JSON_PATH = os.path.join(REPO_ROOT, "verification", "real_desktop_results.json")
OUTPUT_TS_PATH = os.path.join(REPO_ROOT, "src", "data", "verification.ts")
RUNS_DIR = os.path.join(AGENT_DIR, "runs")
PUBLIC_REPLAY_REAL_PATH = os.path.join(REPO_ROOT, "public", "replay_real.json")


def format_timestamp(ts_str: str) -> tuple[str, str]:
    """Parse ISO timestamp to return (YYYY-MM-DD, Month DD, YYYY)."""
    try:
        dt = datetime.datetime.fromisoformat(ts_str)
        iso_date = dt.strftime("%Y-%m-%d")
        human_date = dt.strftime("%B %d, %Y")
        return iso_date, human_date
    except Exception:
        fallback = ts_str.split("T")[0] if "T" in ts_str else ts_str[:10]
        return fallback, fallback


def generate_verification_ts() -> dict[str, Any]:
    """Parse verification/real_desktop_results.json and write src/data/verification.ts."""
    if not os.path.exists(VERIFICATION_JSON_PATH):
        raise FileNotFoundError(f"Verification results not found at: {VERIFICATION_JSON_PATH}")

    with open(VERIFICATION_JSON_PATH, "r", encoding="utf-8") as f:
        raw_results = json.load(f)

    records: dict[str, dict[str, Any]] = {}
    verified_count = 0
    latest_dt: datetime.datetime | None = None
    latest_date_str = ""

    for feature_id, entry in raw_results.items():
        status = entry.get("status", "FAIL")
        is_pass = status == "PASS"
        ts = entry.get("timestamp", "")
        iso_date, human_date = format_timestamp(ts)

        try:
            cur_dt = datetime.datetime.fromisoformat(ts)
            if latest_dt is None or cur_dt > latest_dt:
                latest_dt = cur_dt
                latest_date_str = iso_date
        except Exception:
            if not latest_date_str:
                latest_date_str = iso_date

        if is_pass:
            verified_count += 1
            status_text = f"Unit-tested / Injected ({iso_date}) (Hardware verification pending)"
            status_text_long = f"Unit-tested / Injected ({human_date}) (Hardware verification pending)"
        else:
            status_text = "Not yet verified"
            status_text_long = "Not yet verified"

        records[feature_id] = {
            "feature_id": feature_id,
            "status": status,
            "verified": False,
            "statusText": status_text,
            "statusTextLong": status_text_long,
            "timestamp": ts,
            "date": iso_date,
            "formattedDate": human_date,
            "detail": entry.get("detail", ""),
            "evidence_hash": entry.get("evidence_hash"),
            "screenshot_hash": entry.get("screenshot_hash"),
        }

    all_verified = False

    ts_content = f"""// Generated by scripts/generate_verification_data.py
// Source: verification/real_desktop_results.json
// Do not edit manually. Re-run scripts/generate_verification_data.py to refresh.

export interface VerificationRecord {{
  feature_id: string;
  status: "PASS" | "FAIL" | string;
  verified: boolean;
  statusText: string;
  statusTextLong: string;
  timestamp: string;
  date: string;
  formattedDate: string;
  detail: string;
  evidence_hash: string | null;
  screenshot_hash: string | null;
}}

export type VerificationFeatureId =
{chr(10).join(f'  | "{k}"' for k in records.keys())};

export const VERIFICATION_RESULTS: Record<string, VerificationRecord> = {json.dumps(records, indent=2)};

export const VERIFICATION_ITEMS: VerificationRecord[] = Object.values(VERIFICATION_RESULTS);

export const TOTAL_VERIFIED_COUNT: number = {verified_count};

export const TOTAL_FEATURE_COUNT: number = {len(records)};

export const IS_REAL_DESKTOP_VERIFIED: boolean = {str(all_verified).lower()};

export const LAST_VERIFICATION_DATE: string = {json.dumps(latest_date_str)};

/**
 * Check if a specific feature ID has passed real desktop verification.
 */
export function isDesktopVerified(featureId: string): boolean {{
  return VERIFICATION_RESULTS[featureId]?.verified ?? false;
}}

/**
 * Get human-readable verification status text for a feature ID.
 * Returns 'Verified on a real desktop (date)' if verified, otherwise 'Not yet verified'.
 */
export function getVerificationStatus(featureId: string): string {{
  return VERIFICATION_RESULTS[featureId]?.statusText ?? "Not yet verified";
}}

/**
 * Retrieve full typed verification record for a feature ID.
 */
export function getVerificationRecord(featureId: string): VerificationRecord | undefined {{
  return VERIFICATION_RESULTS[featureId];
}}
"""

    os.makedirs(os.path.dirname(OUTPUT_TS_PATH), exist_ok=True)
    with open(OUTPUT_TS_PATH, "w", encoding="utf-8") as f:
        f.write(ts_content)

    print(f"[OK] Generated {OUTPUT_TS_PATH} ({verified_count}/{len(records)} verified)")
    return records


def find_latest_real_run(runs_dir: str) -> str:
    """Find the latest real run with an audit.jsonl in agent/runs/."""
    if not os.path.exists(runs_dir) or not os.path.isdir(runs_dir):
        raise FileNotFoundError(f"Runs directory not found: {runs_dir}")

    candidates: list[tuple[str, float, str]] = []
    for entry in os.listdir(runs_dir):
        full_dir = os.path.join(runs_dir, entry)
        if not os.path.isdir(full_dir):
            continue
        audit_file = os.path.join(full_dir, "audit.jsonl")
        if not os.path.exists(audit_file):
            continue

        try:
            with open(audit_file, "r", encoding="utf-8") as f:
                first_line = f.readline()
                if not first_line.strip():
                    continue
                data = json.loads(first_line)
                if data.get("mode") == "real":
                    candidates.append((full_dir, os.path.getmtime(full_dir), entry))
        except Exception:
            continue

    if not candidates:
        raise ValueError(f"No real runs with audit.jsonl found in {runs_dir}")

    candidates.sort(key=lambda x: x[1], reverse=True)
    selected_id = candidates[0][2]
    print(f"[OK] Identified latest real run: {selected_id}")
    return selected_id


def export_real_replay() -> dict[str, Any]:
    """Export latest real run as public/replay_real.json and verify it."""
    run_id = find_latest_real_run(RUNS_DIR)
    exported_replay_path = export_replay(RUNS_DIR, run_id)

    if not os.path.exists(exported_replay_path):
        raise FileNotFoundError(f"Replay export failed, missing: {exported_replay_path}")

    # Copy to public/replay_real.json
    os.makedirs(os.path.dirname(PUBLIC_REPLAY_REAL_PATH), exist_ok=True)
    shutil.copyfile(exported_replay_path, PUBLIC_REPLAY_REAL_PATH)

    # Validate public/replay_real.json
    with open(PUBLIC_REPLAY_REAL_PATH, "r", encoding="utf-8") as f:
        replay_data = json.load(f)

    mode = replay_data.get("mode")
    if mode != "real":
        raise ValueError(f"Expected replay mode 'real', got '{mode}' in {PUBLIC_REPLAY_REAL_PATH}")

    events = replay_data.get("events", [])
    print(
        f"[OK] Exported {PUBLIC_REPLAY_REAL_PATH}: mode={mode}, run_id={replay_data.get('run_id')}, events={len(events)}"
    )
    return replay_data


def main() -> None:
    print("=== Generating Verification Data & Real Replay ===")
    generate_verification_ts()
    export_real_replay()
    print("=== Done ===")


if __name__ == "__main__":
    main()
