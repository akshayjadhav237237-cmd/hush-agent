import React, { useState, useEffect } from 'react';
import type { VisualizerStatus } from './types';
import { Network, Code2, ShieldAlert } from 'lucide-react';

export const GraphVisualizer: React.FC = () => {
  const [status, setStatus] = useState<VisualizerStatus>('checking');
  const [blockedUrls, setBlockedUrls] = useState<readonly string[]>([]);

  useEffect(() => {
    let isMounted = true;

    async function checkGraphFile() {
      try {
        const response = await fetch('./graph/graph.html', { method: 'GET' });
        if (!response.ok) {
          if (isMounted) setStatus('missing');
          return;
        }

        const html = await response.text();

        // Check if the server returned an SPA index.html fallback
        const isSpaFallback =
          html.includes('id="root"') ||
          html.includes('src="/src/main.tsx"') ||
          (html.includes('<!doctype html>') && !html.includes('graph'));

        if (isSpaFallback) {
          if (isMounted) setStatus('missing');
          return;
        }

        // Grep for external URLs in script, link, and img tags
        const externalTagRegex =
          /<(script|link|img)[^>]*(?:src|href)=["'](https?:\/\/[^"']+)["'][^>]*>/gi;
        const matches: string[] = [];
        let match: RegExpExecArray | null;

        while ((match = externalTagRegex.exec(html)) !== null) {
          if (match[2]) {
            matches.push(match[2]);
          }
        }

        if (matches.length > 0) {
          if (isMounted) {
            setBlockedUrls(matches);
            setStatus('external_blocked');
          }
          return;
        }

        if (isMounted) {
          setStatus('available');
        }
      } catch {
        if (isMounted) {
          setStatus('missing');
        }
      }
    }

    checkGraphFile();

    return () => {
      isMounted = false;
    };
  }, []);

  if (status === 'available') {
    return (
      <div className="w-full space-y-2">
        <div className="aspect-video rounded-[24px] border border-white/[0.06] bg-[#141414] overflow-hidden relative shadow-2xl">
          <iframe
            sandbox="allow-scripts"
            src="./graph/graph.html"
            title="Interactive Code Graph"
            className="w-full h-full border-0"
          />
        </div>
        <p className="text-center text-xs font-mono text-[#F5F0E8]/45">
          Real graph generated by Graphify from a small demo project.
        </p>
      </div>
    );
  }

  if (status === 'external_blocked') {
    return (
      <div className="w-full space-y-2">
        <div className="aspect-video rounded-[24px] border border-white/[0.06] bg-[#141414] flex flex-col items-center justify-center p-8 text-center relative overflow-hidden shadow-2xl">
          <div className="max-w-md mx-auto space-y-3">
            <div
              className="w-12 h-12 rounded-[16px] bg-white/[0.04] border border-white/[0.08] flex items-center justify-center mx-auto text-[#FFBD2E] mb-2"
              aria-hidden="true"
            >
              <ShieldAlert className="w-6 h-6" strokeWidth={1.5} />
            </div>

            <h3 className="text-base sm:text-lg font-bold font-['Archivo',sans-serif] text-[#F0FFE8] tracking-tight">
              External resource detected
            </h3>

            <p className="text-xs sm:text-sm text-[#F5F0E8]/60 leading-relaxed font-['Space_Grotesk',sans-serif]">
              The graph export contains remote references. Sandboxed offline policy prevents embedding external network resources.
            </p>

            <div className="pt-2 text-left bg-black/60 border border-white/[0.06] rounded-[16px] p-3 max-h-24 overflow-y-auto">
              <span className="block font-mono text-[11px] text-[#F5F0E8]/45 mb-1">
                Detected references:
              </span>
              <ul className="list-disc list-inside font-mono text-[10px] text-[#F5F0E8]/60 space-y-0.5">
                {blockedUrls.map((url) => (
                  <li key={url} className="truncate">
                    {url}
                  </li>
                ))}
              </ul>
            </div>
          </div>
        </div>
        <p className="text-center text-xs font-mono text-[#F5F0E8]/45">
          Sandbox policy requires fully local, self-contained HTML graph artifacts.
        </p>
      </div>
    );
  }

  // Fallback / missing placeholder
  return (
    <div className="w-full space-y-2">
      <div
        className="aspect-video rounded-[24px] border border-white/[0.06] bg-[#141414] flex flex-col items-center justify-center p-8 text-center relative overflow-hidden shadow-2xl"
        role="region"
        aria-label="Code Graph Interactive Viewer Placeholder"
      >
        {/* Subtle decorative grid lines */}
        <div
          className="absolute inset-0 opacity-[0.03] pointer-events-none"
          style={{
            backgroundImage:
              'radial-gradient(circle at 1px 1px, #22FF6E 1px, transparent 0)',
            backgroundSize: '24px 24px',
          }}
          aria-hidden="true"
        />

        <div className="relative z-10 max-w-md mx-auto space-y-3">
          <div
            className="w-12 h-12 rounded-[16px] bg-[#22FF6E]/10 border border-[#22FF6E]/20 flex items-center justify-center mx-auto text-[#22FF6E] mb-2"
            aria-hidden="true"
          >
            <Network className="w-6 h-6" strokeWidth={1.5} />
          </div>

          <h3 className="text-base sm:text-lg font-bold font-['Archivo',sans-serif] text-[#F0FFE8] tracking-tight">
            Graph preview coming soon
          </h3>

          <p className="text-xs sm:text-sm text-[#F5F0E8]/60 leading-relaxed font-['Space_Grotesk',sans-serif]">
            The command{' '}
            <code className="font-mono text-[#22FF6E] bg-black/60 px-2 py-0.5 rounded-[6px] border border-white/[0.08]">
              graphify export html
            </code>{' '}
            generates this interactive visualization during local runs.
          </p>

          <div className="pt-2">
            <span className="inline-flex items-center gap-1.5 px-3 py-1 rounded-[10px] text-[11px] font-mono text-[#F5F0E8]/70 bg-white/[0.04] border border-white/[0.08]">
              <Code2 className="w-3.5 h-3.5 text-[#22FF6E]" strokeWidth={1.5} aria-hidden="true" />
              <span>Artifact path: graphify-out/graph.html</span>
            </span>
          </div>
        </div>
      </div>
      <p className="text-center text-xs font-mono text-[#F5F0E8]/45">
        AST visualization generated locally from workspace source files.
      </p>
    </div>
  );
};
